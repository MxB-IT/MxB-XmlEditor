"""Contains a class defining all the colour hexes needed for the GUI."""

from enum import StrEnum


class ColourEnum(StrEnum):
    """Enum class containing all the colours used in the GUI as hex codes."""

    MXB_RED = "#b34f4c"
    DARK_MXB_RED = "#883c3a"
    DARKER_MXB_RED = "#5b2826"
    WHITE = "#ffffff"
    RED = "#ff0000"
    GREEN = "#008000"
